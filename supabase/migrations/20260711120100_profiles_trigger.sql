-- Creates a matching public.profiles row whenever a new auth.users row is
-- inserted (covers both email/password signup and OAuth signup). Runs as
-- security definer so it can write to public.profiles regardless of the
-- caller's RLS grants.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', new.email)
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
